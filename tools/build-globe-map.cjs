'use strict';

// Rebuild the checked-in, same-origin map bundle from pinned npm packages.
const fs = require('node:fs');
const path = require('node:path');
const zlib = require('node:zlib');
const { buildSync } = require('esbuild');
const { feature } = require('topojson-client');
const root = path.resolve(__dirname, '..');
const atlas = JSON.parse(fs.readFileSync(require.resolve('world-atlas/land-110m.json'), 'utf8'));
const land = feature(atlas, atlas.objects.land);
// 0.001 degrees is well below one pixel on this sidebar globe.
const geometry = JSON.stringify(land, (_, value) => typeof value === 'number' ? Math.round(value * 1000) / 1000 : value);
const output = path.join(root, 'source/js/vendor/luomo-geo.min.js');
fs.mkdirSync(path.dirname(output), { recursive: true });
buildSync({
  stdin: {
    contents: `export {geoOrthographic, geoPath} from 'd3-geo'; export const land = ${geometry};`,
    resolveDir: root,
    sourcefile: 'luomo-geo-entry.js'
  },
  outfile: output,
  bundle: true,
  minify: true,
  format: 'iife',
  globalName: 'LuomoGeo',
  target: ['es2020'],
  legalComments: 'inline',
  banner: { js: '/*! Natural Earth land via world-atlas 2.0.2; d3-geo 3.1.1. See luomo-geo.LICENSE.txt. */' }
});

const notices = [
  'World land: Natural Earth, public domain. https://www.naturalearthdata.com/about/terms-of-use/',
  'Redistributed via world-atlas 2.0.2. Coordinates rounded to 0.001 degrees for a small display.',
  'Projection: d3-geo; only geoOrthographic and geoPath plus their dependencies are bundled.',
  'Generated by tools/build-globe-map.cjs. Versions are pinned in package.json and pnpm-lock.yaml.'
];
for (const name of ['world-atlas', 'topojson-client', 'd3-geo', 'd3-array', 'internmap']) {
  // Resolve through the owning package so pnpm's isolated dependencies also work.
  let entry;
  if (name === 'world-atlas') entry = require.resolve('world-atlas/land-110m.json');
  else if (name === 'd3-array') entry = require.resolve(name, { paths: [path.dirname(require.resolve('d3-geo'))] });
  else if (name === 'internmap') entry = require.resolve(name, { paths: [path.dirname(require.resolve('d3-array', { paths: [path.dirname(require.resolve('d3-geo'))] }))] });
  else entry = require.resolve(name);
  let directory = path.dirname(entry);
  while (!fs.existsSync(path.join(directory, 'LICENSE'))) {
    const parent = path.dirname(directory);
    if (parent === directory) throw new Error(`Missing license for ${name}`);
    directory = parent;
  }
  notices.push(`\n===== ${name} =====\n${fs.readFileSync(path.join(directory, 'LICENSE'), 'utf8')}`);
}
fs.writeFileSync(path.join(path.dirname(output), 'luomo-geo.LICENSE.txt'), notices.join('\n').trimEnd() + '\n');
const bytes = fs.readFileSync(output);
console.log(`World map bundle: ${bytes.length} bytes (${zlib.gzipSync(bytes).length} gzip), ${land.features.length} land feature(s).`);
